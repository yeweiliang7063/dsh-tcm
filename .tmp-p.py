import io
p='cordis.patch.yml'
s=io.open(p,encoding='utf-8').read()
old='                - 拿到病人名字后：医生发来的每一句都当问诊继续——调 send_message 转给病人，再用 wait_agent 等病人回话；拿到原话后只把它带回给医生，不评价、不提示还应问什么。医生要看舌、要切脉时，把要求一并转给病人，由病人照病例卡报舌象与脉象；你只照原话转回，不自己补——你心里想到的方名、条文、刚才查到的任何东西，一个字都不许写进面板，也不许借病人的嘴说出来。医生说到治法、方药、取穴，也只是他在说，你照样不点评、不接话，等他说「交卷」。'
new='                - 拿到病人名字后，医生每发一句话，你只看它属于哪一类，三选一，不许自己加戏：①是问句（带问号，或「吗／呢／是不是／要不要／有没有／怎么／多少」这类问法，或者「请把舌头伸出来」「我摸一下脉」这种要病人配合的动作要求）——调 send_message 转给病人，再用 wait_agent 等回话，拿到原话后照原样带回，不评价、不提示还应问什么；你心里想到的方名、条文、查到的任何东西，一个字都不许写进面板，也不许借病人的嘴说出来。②是在答题（陈述症状、讲病机、写治法方药、取穴、整段分析）——这一段他还没说完，你什么都不做：不调 send_message、不调 subagent、不点评、不追问、不写旁白，正文一个字都不写，直接结束这一轮，等他的下一句。③是「交卷」——才切裁判。'
assert old in s
s=s.replace(old,new,1)
old2='                - 病人这句话要是没答到点上，可以再转一句追问；但判断、总结、提示都不归你。'
new2='                - 病人这句话要是没答到点上，可以再转一句追问；但判断、总结、提示都不归你。\n                - 【答题期间病人和裁判都不许插话】医生在答题（没问句、没说「交卷」）的时候，病人不许自己开口，裁判不许提前点评，你也不许替任何一方说话。只有医生问了、上面转过去了，病人才有话说；只有医生说了「交卷」，裁判才有话。'
